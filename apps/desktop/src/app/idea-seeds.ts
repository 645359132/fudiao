/** 由作者填的类型找最接近的一组；对不上（或没填）时随机挑一组。 */
function poolFor(genre: string, random: () => number): IdeaPool {
  const g = genre.trim();
  // 按两个字的片段比：“悬疑推理”对上“古风悬疑”，“现代都市”对上“都市”。
  const pairs = (text: string) => [...text].slice(0, -1).map((ch, i) => ch + text[i + 1]!);
  const matched = g === '' ? undefined : IDEA_POOLS.find((p) => p.genre.includes(g) || g.includes(p.genre) || pairs(p.genre).some((pair) => g.includes(pair)));
  return matched ?? pick(IDEA_POOLS, random);
}

function pick<T>(list: readonly T[], random: () => number): T {
  return list[Math.min(list.length - 1, Math.floor(random() * list.length))]!;
}

/** 随机拼一句想法；作者没填类型时一并给出这组的类型。 */
export function randomIdea(genre: string, random: () => number): { readonly idea: string; readonly genre: string } {
  const pool = poolFor(genre, random);
  return { idea: `${pick(pool.who, random)}${pick(pool.situation, random)}，${pick(pool.twist, random)}`, genre: genre.trim() === '' ? pool.genre : genre };
}
